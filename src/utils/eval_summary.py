"""
eval_summary.py
----------------
Generates data/eval/SUMMARY.md — a single, human-readable index of every
compliance eval run archived under data/eval/runs/.

Individual run files are the source of truth (one per run, never overwritten);
this module just regenerates a readable view over them. Safe to re-run any
time — always rebuilds the file from scratch off the current archive.

Run schema (as of the 4-level verdict scale + model comparison work):
{
  "run_at": ISO timestamp,
  "model": "gpt-4o-mini",
  "set_type": "main" | "holdout",
  "note": str,
  "metrics": {...ordinal metrics from compute_ordinal_metrics...},
  "by_category": {...},
  "predictions": [...],
}
"""

from __future__ import annotations

import json
from pathlib import Path


def _load_runs(runs_dir: Path) -> list[dict]:
    runs = []
    for path in sorted(runs_dir.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if "metrics" not in data or "exact_match_accuracy" not in data.get("metrics", {}):
            continue  # skip legacy binary-scheme run files, incompatible schema
        runs.append({
            "file": path.name,
            "run_at": data.get("run_at", "unknown"),
            "model": data.get("model", "unknown"),
            "set_type": data.get("set_type", "main"),
            "note": data.get("note", ""),
            "metrics": data["metrics"],
        })
    runs.sort(key=lambda r: r["run_at"])
    return runs


def _fmt_pct(x: float) -> str:
    return f"{x:.1%}"


def generate_eval_summary(eval_dir: str = "data/eval") -> Path:
    """
    Scan data/eval/runs/*.json and regenerate data/eval/SUMMARY.md.

    Returns the path to the written summary file.
    """
    eval_path = Path(eval_dir)
    runs_dir = eval_path / "runs"
    runs = _load_runs(runs_dir)

    lines = [
        "# Compliance checker — evaluation history",
        "",
        "Auto-generated by `src/utils/eval_summary.py` from `data/eval/runs/*.json`. "
        "Do not edit by hand — re-run the generator instead (see notebook 06, final cell).",
        "",
        "Verdict scale: 0=fully compliant, 1=compliant with a minor note, "
        "2=grey area (needs legal review), 3=not compliant. "
        "`off_by_one_accuracy` tolerates a 1-level miss (e.g. predicting 1 when truth is 0); "
        "`severe_miss_rate` is the failure mode that actually matters — predicting a real "
        "violation as compliant, or vice versa (|predicted - truth| >= 2).",
        "",
        "## All runs",
        "",
        "| Date (UTC) | Model | Set | N | Exact match | Off-by-1 | Severe miss | MAE | Notes |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    for r in runs:
        date = r["run_at"].replace("T", " ")[:16]
        note = r["note"] or "—"
        m = r["metrics"]
        set_label = "Holdout" if r["set_type"] == "holdout" else "Main"
        lines.append(
            f"| {date} | {r['model']} | {set_label} | {m['n']} | "
            f"{_fmt_pct(m['exact_match_accuracy'])} | {_fmt_pct(m['off_by_one_accuracy'])} | "
            f"{_fmt_pct(m['severe_miss_rate'])} | {m['mean_absolute_error']:.3f} | {note} |"
        )

    lines += [
        "",
        "## Where the full detail lives",
        "",
        "- `data/eval/runs/<timestamp>_<model>_<set>.json` — one file per run, full "
        "predictions and per-example reasoning, never overwritten.",
        "- `data/eval/compliance_results.json` — latest main (fitted) set run.",
        "- `data/eval/compliance_holdout_results.json` — latest holdout (unseen) set run.",
        "- `data/eval/compliance_labeled_set.json` / `compliance_holdout_set.json` — the "
        "test sets themselves, with ground-truth labels and rationale per claim.",
        "",
    ]

    summary_path = eval_path / "SUMMARY.md"
    summary_path.write_text("\n".join(lines), encoding="utf-8")
    return summary_path


if __name__ == "__main__":
    path = generate_eval_summary()
    print(f"Wrote {path}")
