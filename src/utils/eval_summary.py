"""
eval_summary.py
----------------
Generates data/eval/SUMMARY.md — a single, human-readable index of every
compliance eval run archived under data/eval/runs/.

Individual run files are the source of truth (one per run, never overwritten);
this module just regenerates a readable view over them. Safe to re-run any
time — always rebuilds the file from scratch off the current archive.
"""

from __future__ import annotations

import json
from pathlib import Path


def _load_runs(runs_dir: Path) -> list[dict]:
    runs = []
    for path in sorted(runs_dir.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        is_holdout = "full_system" not in data
        metrics = data["metrics"] if is_holdout else data["full_system"]["metrics"]
        runs.append({
            "file": path.name,
            "run_at": data.get("run_at", "unknown"),
            "type": "Holdout (unseen)" if is_holdout else "Main (fitted)",
            "note": data.get("note", ""),
            "n": metrics["n"],
            "accuracy": metrics["accuracy"],
            "precision": metrics["precision"],
            "recall": metrics["recall"],
            "f1": metrics["f1"],
            "layer2_comparison": data.get("layer2_comparison"),
        })
    runs.sort(key=lambda r: r["run_at"])
    return runs


def _fmt_pct(x: float) -> str:
    return f"{x:.1%}"


def generate_eval_summary(eval_dir: str = "data/eval") -> Path:
    """
    Scan data/eval/runs/*.json and regenerate data/eval/SUMMARY.md.

    Returns the path to the written summary file.
    """
    eval_path = Path(eval_dir)
    runs_dir = eval_path / "runs"
    runs = _load_runs(runs_dir)

    lines = [
        "# Compliance checker — evaluation history",
        "",
        "Auto-generated by `src/utils/eval_summary.py` from `data/eval/runs/*.json`. "
        "Do not edit by hand — re-run the generator instead (see notebook 06, final cell).",
        "",
        "## All runs",
        "",
        "| Date (UTC) | Type | N | Accuracy | Precision | Recall | F1 | Notes |",
        "|---|---|---|---|---|---|---|---|",
    ]

    for r in runs:
        date = r["run_at"].replace("T", " ")[:16]
        note = r["note"] or "—"
        lines.append(
            f"| {date} | {r['type']} | {r['n']} | {_fmt_pct(r['accuracy'])} | "
            f"{r['precision']:.3f} | {r['recall']:.3f} | {r['f1']:.3f} | {note} |"
        )

    layer2_runs = [r for r in runs if r["layer2_comparison"]]
    if layer2_runs:
        lines += [
            "",
            "## Layer-2 comparison (RAG-grounded vs. ungrounded classifier)",
            "",
            "Isolates the LLM decision on claims that dodge the blocklist — the specific "
            "comparison that justifies RAG grounding over an ungrounded LLM classifier.",
            "",
            "| Date (UTC) | Classifier | Accuracy | Precision | Recall | F1 |",
            "|---|---|---|---|---|---|",
        ]
        for r in layer2_runs:
            date = r["run_at"].replace("T", " ")[:16]
            u = r["layer2_comparison"]["ungrounded_metrics"]
            g = r["layer2_comparison"]["grounded_metrics"]
            lines.append(
                f"| {date} | Ungrounded | {_fmt_pct(u['accuracy'])} | {u['precision']:.3f} | "
                f"{u['recall']:.3f} | {u['f1']:.3f} |"
            )
            lines.append(
                f"| {date} | **RAG-grounded** | **{_fmt_pct(g['accuracy'])}** | "
                f"**{g['precision']:.3f}** | **{g['recall']:.3f}** | **{g['f1']:.3f}** |"
            )

    lines += [
        "",
        "## Where the full detail lives",
        "",
        "- `data/eval/runs/<timestamp>[_label].json` — one file per run, full predictions "
        "and per-example reasoning, never overwritten.",
        "- `data/eval/compliance_results.json` — latest main (fitted) set run.",
        "- `data/eval/compliance_holdout_results.json` — latest holdout (unseen) set run.",
        "- `data/eval/compliance_labeled_set.json` / `compliance_holdout_set.json` — the "
        "test sets themselves, with ground-truth labels and rationale per claim.",
        "",
    ]

    summary_path = eval_path / "SUMMARY.md"
    summary_path.write_text("\n".join(lines), encoding="utf-8")
    return summary_path


if __name__ == "__main__":
    path = generate_eval_summary()
    print(f"Wrote {path}")
